function seed() {
  console.log(`Generating 90%+ match scoring for ${MASTER_INDIAN_GLOBAL_JOBS.length} master openings...`);
  const profile = profileService.getProfile();

  const scored = MASTER_INDIAN_GLOBAL_JOBS.map(job => {
    const match = jobMatcherService.evaluateMatch(job, profile);
    return {
      ...job,
      matchScore: match.overallScore,
      matchBreakdown: match.breakdown,
      matchReasons: match.reasons,
      fintechMatchDetails: match.fintechMatchDetails,
      hasAlreadyApplied: false,
      isActive: true,
      discoveredAt: new Date().toISOString()
    };
  });

  // Sort descending by match score
  scored.sort((a, b) => b.matchScore - a.matchScore);

  fs.writeFileSync(JOBS_FILE, JSON.stringify(scored, null, 2), 'utf8');
  console.log(`✓ Successfully seeded ${scored.length} verified Indian & Global SDET/QA/Manual/Fintech jobs into jobs.json!`);
  console.log('Sample Scores:');
  scored.slice(0, 5).forEach(j => {
    console.log(`- [${j.matchScore}% Match] ${j.title} at ${j.company} (${j.location}) | Salary: ${j.salary}`);
  });
}

seed();
